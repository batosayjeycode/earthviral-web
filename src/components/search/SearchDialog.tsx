/**
 * Static client search (FR-09) over the Pagefind index built after `astro build`.
 *
 *   dialog mode — opened by ⌘K / Ctrl+K, "/" or any [data-search-trigger] link (which
 *                 falls back to /search/ when JavaScript is unavailable)
 *   page mode   — the /search/ page (target of the WebSite SearchAction), reads ?q=
 *
 * Pagefind's runtime (/pagefind/pagefind.js) is imported on first use only.
 */
import { useCallback, useEffect, useId, useRef, useState } from 'react';

interface PagefindResultData {
  url: string;
  excerpt: string;
  meta: { title?: string; country?: string; score?: string };
}
interface Pagefind {
  init?: () => Promise<void>;
  debouncedSearch: (
    q: string,
    opts?: object,
    ms?: number,
  ) => Promise<{ results: Array<{ data: () => Promise<PagefindResultData> }> } | null>;
}

let pagefindPromise: Promise<Pagefind> | null = null;
function loadPagefind(): Promise<Pagefind> {
  pagefindPromise ??= import(/* @vite-ignore */ `${'/pagefind/pagefind.js'}`)
    .then(async (pf: Pagefind) => {
      await pf.init?.();
      return pf;
    })
    .catch((err) => {
      pagefindPromise = null;
      throw err;
    });
  return pagefindPromise;
}

type Status = 'idle' | 'loading' | 'ready' | 'unavailable';

const NO_RESULTS: PagefindResultData[] = [];

/**
 * Results are stored together with the query they answer; everything else (idle, loading)
 * is derived during render, so the effect only sets state from async callbacks.
 */
function useSearch(query: string): { results: PagefindResultData[]; status: Status } {
  const q = query.trim();
  const [answer, setAnswer] = useState<{
    q: string;
    results: PagefindResultData[];
    status: Status;
  }>({
    q: '',
    results: NO_RESULTS,
    status: 'idle',
  });

  useEffect(() => {
    if (!q) return;
    let cancelled = false;
    loadPagefind()
      .then(async (pf) => {
        const search = await pf.debouncedSearch(q, {}, 200);
        if (!search || cancelled) return; // superseded by a newer keystroke
        const data = await Promise.all(search.results.slice(0, 8).map((r) => r.data()));
        if (!cancelled) setAnswer({ q, results: data, status: 'ready' });
      })
      .catch(() => {
        if (!cancelled) setAnswer({ q, results: NO_RESULTS, status: 'unavailable' });
      });
    return () => {
      cancelled = true;
    };
  }, [q]);

  if (!q) return { results: NO_RESULTS, status: 'idle' };
  if (answer.status === 'unavailable') return { results: NO_RESULTS, status: 'unavailable' };
  // Keep showing the previous results while the next query loads (no flash of "Searching…").
  return { results: answer.results, status: answer.q === q ? answer.status : 'loading' };
}

function Results({
  query,
  results,
  status,
  active,
  listId,
  onHover,
}: {
  query: string;
  results: PagefindResultData[];
  status: Status;
  active: number;
  listId: string;
  onHover: (i: number) => void;
}) {
  if (status === 'unavailable') {
    return (
      <p className="px-4 py-6 text-sm text-ink-muted">
        Search isn’t available here. The index is generated by <code>npm run build</code> — it
        doesn’t exist in <code>astro dev</code>.
      </p>
    );
  }
  if (!query.trim())
    return (
      <p className="px-4 py-6 text-sm text-ink-faint">Search stories, countries and topics.</p>
    );
  if (status === 'loading' && results.length === 0)
    return <p className="px-4 py-6 text-sm text-ink-faint">Searching…</p>;
  if (results.length === 0)
    return <p className="px-4 py-6 text-sm text-ink-muted">No stories match “{query}”.</p>;
  return (
    <ul id={listId} role="listbox" aria-label="Search results" className="grid gap-1 p-2">
      {results.map((r, i) => (
        <li key={r.url} role="option" aria-selected={i === active} id={`${listId}-${i}`}>
          <a
            href={r.url}
            onMouseEnter={() => onHover(i)}
            className={`block rounded-lg px-3 py-2.5 ${i === active ? 'bg-cyan/10' : 'hover:bg-white/5'}`}
          >
            <span className="flex items-center gap-2">
              <span className="font-display font-semibold text-white">{r.meta.title ?? r.url}</span>
              {r.meta.score && (
                <span className="tabular ml-auto shrink-0 text-xs text-cyan">{r.meta.score}</span>
              )}
            </span>
            {r.meta.country && <span className="text-xs text-ink-faint">{r.meta.country}</span>}
            {/* Pagefind excerpts are built from our own pages and only contain <mark> highlights. */}
            <span
              className="ev-excerpt mt-1 block text-sm text-ink-muted"
              dangerouslySetInnerHTML={{ __html: r.excerpt }}
            />
          </a>
        </li>
      ))}
    </ul>
  );
}

function useKeyboardNav(results: PagefindResultData[]) {
  // The highlighted row resets to 0 whenever the result list changes (derived, not effect-driven).
  const [nav, setNav] = useState({ results, active: 0 });
  const active = nav.results === results ? nav.active : 0;
  const setActive = (next: number | ((i: number) => number)) =>
    setNav((n) => {
      const current = n.results === results ? n.active : 0;
      return { results, active: typeof next === 'function' ? next(current) : next };
    });
  const onKeyDown = (e: React.KeyboardEvent) => {
    if (e.key === 'ArrowDown') {
      e.preventDefault();
      setActive((i) => Math.min(results.length - 1, i + 1));
    } else if (e.key === 'ArrowUp') {
      e.preventDefault();
      setActive((i) => Math.max(0, i - 1));
    } else if (e.key === 'Enter' && results[active]) {
      e.preventDefault();
      window.location.href = results[active].url;
    }
  };
  return { active, setActive, onKeyDown };
}

function SearchInput(props: {
  value: string;
  onChange: (v: string) => void;
  onKeyDown: (e: React.KeyboardEvent) => void;
  listId: string;
  activeId: string | undefined;
  /** True only while the results listbox is rendered (aria-controls must point at it). */
  expanded: boolean;
  autoFocus?: boolean;
}) {
  return (
    <div className="flex items-center gap-3 border-b border-line px-4">
      <svg
        aria-hidden="true"
        viewBox="0 0 20 20"
        className="size-5 shrink-0 text-ink-faint"
        fill="none"
        stroke="currentColor"
        strokeWidth="1.8"
      >
        <circle cx="9" cy="9" r="6" />
        <path d="m14 14 4 4" />
      </svg>
      <input
        type="search"
        role="combobox"
        aria-expanded={props.expanded}
        aria-controls={props.expanded ? props.listId : undefined}
        aria-activedescendant={props.expanded ? props.activeId : undefined}
        aria-label="Search EarthViral"
        placeholder="Search stories, countries, topics…"
        autoFocus={props.autoFocus}
        value={props.value}
        onChange={(e) => props.onChange(e.target.value)}
        onKeyDown={props.onKeyDown}
        className="h-14 w-full bg-transparent text-base text-white outline-none placeholder:text-ink-faint"
      />
    </div>
  );
}

export default function SearchDialog({ mode = 'dialog' }: { mode?: 'dialog' | 'page' }) {
  const dialogRef = useRef<HTMLDialogElement>(null);
  // Page mode is rendered client-only (see /search/), so ?q= can seed the initial state.
  const [query, setQuery] = useState(() =>
    mode === 'page' && typeof window !== 'undefined'
      ? (new URLSearchParams(window.location.search).get('q') ?? '')
      : '',
  );
  const { results, status } = useSearch(query);
  const { active, setActive, onKeyDown } = useKeyboardNav(results);
  const listId = useId();
  const activeId = results.length ? `${listId}-${active}` : undefined;

  const open = useCallback(() => {
    const dialog = dialogRef.current;
    if (!dialog || dialog.open) return;
    dialog.showModal();
    void loadPagefind().catch(() => {}); // warm the index while the user types
  }, []);

  // Page mode: keep the URL shareable.
  useEffect(() => {
    if (mode !== 'page') return;
    const url = new URL(window.location.href);
    if (query) url.searchParams.set('q', query);
    else url.searchParams.delete('q');
    window.history.replaceState(null, '', url);
  }, [mode, query]);

  // Dialog mode: global shortcuts + progressive-enhancement triggers.
  useEffect(() => {
    if (mode !== 'dialog') return;
    const onKey = (e: KeyboardEvent) => {
      const target = e.target as HTMLElement | null;
      const typing =
        target && (target.isContentEditable || /^(INPUT|TEXTAREA|SELECT)$/.test(target.tagName));
      if ((e.key === 'k' || e.key === 'K') && (e.metaKey || e.ctrlKey)) {
        e.preventDefault();
        open();
      } else if (e.key === '/' && !typing) {
        e.preventDefault();
        open();
      }
    };
    const onClick = (e: MouseEvent) => {
      const trigger = (e.target as HTMLElement).closest('[data-search-trigger]');
      if (!trigger || e.metaKey || e.ctrlKey || e.shiftKey) return; // let modified clicks open /search/
      e.preventDefault();
      open();
    };
    window.addEventListener('keydown', onKey);
    document.addEventListener('click', onClick);
    return () => {
      window.removeEventListener('keydown', onKey);
      document.removeEventListener('click', onClick);
    };
  }, [mode, open]);

  const body = (
    <>
      <SearchInput
        value={query}
        onChange={setQuery}
        onKeyDown={(e) => {
          // In a type=search input Chrome's first Escape only clears the text and swallows the
          // dialog's cancel event, so close explicitly.
          if (e.key === 'Escape' && mode === 'dialog') {
            e.preventDefault();
            dialogRef.current?.close();
            return;
          }
          onKeyDown(e);
        }}
        listId={listId}
        activeId={activeId}
        expanded={results.length > 0}
        autoFocus
      />
      <div className="max-h-[60vh] overflow-y-auto">
        <Results
          query={query}
          results={results}
          status={status}
          active={active}
          listId={listId}
          onHover={setActive}
        />
      </div>
    </>
  );

  if (mode === 'page') {
    return <div className="glass overflow-hidden rounded-2xl">{body}</div>;
  }

  return (
    <dialog
      ref={dialogRef}
      aria-label="Search"
      className="ev-search glass m-auto mt-[12vh] w-[min(640px,calc(100vw-2rem))] overflow-hidden rounded-2xl p-0 text-ink backdrop:bg-void/70 backdrop:backdrop-blur-sm"
      onClick={(e) => e.target === dialogRef.current && dialogRef.current?.close()}
      onClose={() => setQuery('')}
    >
      {body}
      <p className="flex justify-between border-t border-line px-4 py-2 text-xs text-ink-faint">
        <span>↑↓ to navigate · Enter to open</span>
        <span>Esc to close</span>
      </p>
    </dialog>
  );
}
